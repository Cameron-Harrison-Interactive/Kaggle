def _align_hands(action,obs):
    farm=_farm(obs,_seat(obs))
    n=len(_get(farm,"hands",[]) or [])
    hands=list(_get(action,"hands",[]) or [])
    if len(hands)<n: hands+=[["PASS"] for _ in range(n-len(hands))]
